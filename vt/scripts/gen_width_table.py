#!/usr/bin/env python3
"""Generates vt/src/main/java/io/github/ghosthack/microhm/vt/WidthTable.java.

Usage (dev time only; the generated file is committed):

    curl -sfSLO https://www.unicode.org/Public/17.0.0/ucd/EastAsianWidth.txt
    curl -sfSLO https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt
    curl -sfSLO https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedGeneralCategory.txt
    python3 -I vt/scripts/gen_width_table.py EastAsianWidth.txt emoji-data.txt \
        DerivedGeneralCategory.txt > vt/src/main/java/io/github/ghosthack/microhm/vt/WidthTable.java

Rules (the usual wcwidth ones, Unicode 9+ emoji widening, as widecharwidth/jediterm do):
  * width 0: general category Mn, Me or Cf (except U+00AD SOFT HYPHEN), plus the Hangul
    Jungseong/Jongseong U+1160..U+11FF; these attach to the previous cell;
  * width 2: East_Asian_Width W or F, or Emoji_Presentation=Yes;
  * everything else (including East Asian Ambiguous and unassigned code points) is 1.
A zero-width property wins over a wide one (e.g. U+3099 COMBINING KATAKANA-HIRAGANA VOICED
SOUND MARK is Mn and W).
"""
import re
import sys

LINE = re.compile(r'^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z_]+)')


def ranges(path, wanted):
    out = set()
    with open(path, encoding='utf-8') as f:
        for raw in f:
            m = LINE.match(raw)
            if not m or m.group(3) not in wanted:
                continue
            lo = int(m.group(1), 16)
            hi = int(m.group(2), 16) if m.group(2) else lo
            out.update(range(lo, hi + 1))
    return out


def merge(points):
    result = []
    for cp in sorted(points):
        if result and result[-1][1] == cp - 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


def java_array(name, rs):
    body = []
    line = '           '
    for lo, hi in rs:
        item = ' 0x%X, 0x%X,' % (lo, hi)
        if len(line) + len(item) > 100:
            body.append(line)
            line = '           '
        line += item
    body.append(line)
    return '    static final int[] %s = {\n%s\n    };\n' % (name, '\n'.join(body))


def main():
    eaw, emoji, gc = sys.argv[1:4]
    zero = ranges(gc, {'Mn', 'Me', 'Cf'})
    zero.discard(0x00AD)
    zero.update(range(0x1160, 0x1200))
    wide = ranges(eaw, {'W', 'F'}) | ranges(emoji, {'Emoji_Presentation'})
    wide -= zero
    print('''package io.github.ghosthack.microhm.vt;

/**
 * GENERATED by vt/scripts/gen_width_table.py from the Unicode 17.0.0 data files
 * (EastAsianWidth.txt, emoji-data.txt, DerivedGeneralCategory.txt); do not edit by hand.
 * Sorted, non-overlapping, inclusive {@code [first, last]} code point pairs; see
 * {@link CharWidth} for how they are used.
 */
final class WidthTable {

    /** Zero width: Mn, Me, Cf (minus U+00AD) and U+1160..U+11FF. */''')
    print(java_array('ZERO', merge(zero)))
    print('    /** Two columns: East_Asian_Width W/F, or Emoji_Presentation. */')
    print(java_array('WIDE', merge(wide)))
    print('''    private WidthTable() {
    }
}''')


if __name__ == '__main__':
    main()
